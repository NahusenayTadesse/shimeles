/**
 * Emits a standalone seeder for the Privacy Policy and Terms pages.
 *
 * Production must not have the whole seed run against it — that would insert
 * blog posts, testimonials and media the Foundation has not asked for. This
 * pulls just those two pages, their single rich-text block each, and their
 * footer navigation links out of the local database (where they have already
 * been rendered and checked) and writes a script that inserts exactly those
 * rows and nothing else.
 *
 * Reading from the local database rather than re-importing `legal-content.ts`
 * is deliberate: what ships is then byte-identical to what was verified in a
 * browser, rather than a second rendering of the same source that could drift.
 *
 *   node scripts/make-legal-seed.mjs   # writes deploy/seed-legal.mjs
 */
import Database from 'better-sqlite3';
import fs from 'node:fs';
import path from 'node:path';

const url = process.env.DATABASE_URL;
if (!url) throw new Error('DATABASE_URL is not set');

const db = new Database(url, { readonly: true });

const SLUGS = ['privacy', 'terms'];

const pages = db
	.prepare(
		`select slug, title, meta_description, is_published, sort_order
		 from pages where slug in (${SLUGS.map(() => '?').join(',')})`
	)
	.all(...SLUGS);

if (pages.length !== SLUGS.length) {
	throw new Error(`expected ${SLUGS.length} pages locally, found ${pages.length}`);
}

const blocks = db
	.prepare(
		`select p.slug as page_slug, b.block_type, b.heading, b.sort_order, b.content
		 from content_blocks b join pages p on p.id = b.page_id
		 where p.slug in (${SLUGS.map(() => '?').join(',')})
		 order by p.slug, b.sort_order`
	)
	.all(...SLUGS);

const nav = db
	.prepare(
		`select n.label, n.placement, n.sort_order, p.slug as page_slug
		 from navigation_items n join pages p on p.id = n.page_id
		 where p.slug in (${SLUGS.map(() => '?').join(',')})`
	)
	.all(...SLUGS);

const payload = JSON.stringify({ pages, blocks, nav }, null, '\t');

const script = `/**
 * Seeds ONLY the Privacy Policy and Terms & Conditions pages.
 *
 * Generated by \`scripts/make-legal-seed.mjs\` from a local database whose
 * copies of these two pages had already been rendered and checked. Do not edit
 * by hand — regenerate it.
 *
 * Scope is deliberately narrow. This inserts two \`pages\` rows, one
 * \`content_blocks\` row each, and their two footer \`navigation_items\`. It
 * touches nothing else, and it is insert-only: a page, block or nav item that
 * already exists is left exactly as it is, so re-running cannot overwrite an
 * edit made through the dashboard.
 *
 *   node seed-legal.mjs
 */
import Database from 'better-sqlite3';

const db = new Database('local.db');
const now = () => Date.now();

const DATA = ${payload};

let addedPages = 0;
let addedBlocks = 0;
let addedNav = 0;

const findPage = db.prepare('select id from pages where slug = ?');

db.transaction(() => {
	for (const page of DATA.pages) {
		if (findPage.get(page.slug)) continue;
		db.prepare(
			\`insert into pages (slug, title, meta_description, is_published, sort_order,
			                    is_active, created_at, updated_at)
			 values (?, ?, ?, ?, ?, 1, ?, ?)\`
		).run(
			page.slug,
			page.title,
			page.meta_description,
			page.is_published,
			page.sort_order,
			now(),
			now()
		);
		addedPages++;
	}

	for (const block of DATA.blocks) {
		const page = findPage.get(block.page_slug);
		if (!page) continue;

		// Keyed on the page rather than on the content: if this page already
		// has any block, someone has been editing it and this must not add a
		// duplicate underneath their work.
		const existing = db
			.prepare('select count(*) as n from content_blocks where page_id = ?')
			.get(page.id);
		if (existing.n > 0) continue;

		db.prepare(
			\`insert into content_blocks (page_id, block_type, heading, sort_order, content,
			                             is_published, is_active, created_at, updated_at)
			 values (?, ?, ?, ?, ?, 1, 1, ?, ?)\`
		).run(
			page.id,
			block.block_type,
			block.heading,
			block.sort_order,
			block.content,
			now(),
			now()
		);
		addedBlocks++;
	}

	for (const item of DATA.nav) {
		const page = findPage.get(item.page_slug);
		if (!page) continue;

		// Keyed on label, the same way the main seeder keys navigation.
		const existing = db.prepare('select id from navigation_items where label = ?').get(item.label);
		if (existing) continue;

		db.prepare(
			\`insert into navigation_items (label, page_id, url, placement, is_cta, sort_order,
			                               is_visible, is_active, created_at, updated_at)
			 values (?, ?, NULL, ?, 0, ?, 1, 1, ?, ?)\`
		).run(item.label, page.id, item.placement, item.sort_order, now(), now());
		addedNav++;
	}
})();

console.log(
	\`legal pages: +\${addedPages} pages, +\${addedBlocks} blocks, +\${addedNav} nav items\`
);
console.log('(0 across the board means they were already present — nothing was overwritten)');
db.close();
`;

const out = path.resolve('deploy/seed-legal.mjs');
fs.writeFileSync(out, script);
console.log(`wrote ${out}`);
console.log(
	`  pages: ${pages.map((p) => p.slug).join(', ')}` +
		`  blocks: ${blocks.length}  nav: ${nav.map((n) => n.label).join(', ')}`
);
