/**
 * Emits a standalone seeder for the in-kind giving catalogue.
 *
 * Migration 0014 creates `in_kind_categories` empty. The "Give goods" tab on
 * the donate page is built entirely from that table, so migrating alone ships
 * a form with nothing to offer — and the dashboard's queue would have no
 * vocabulary to describe what arrived. This carries the rows across.
 *
 * It also carries the two new permissions and their role grants. Those are
 * seeded from `PERMISSIONS` in code rather than typed by anybody, so on the
 * server they are exactly as much "configuration rows the feature cannot work
 * without" as the categories are: without them, Finance and Program Staff open
 * the dashboard and get a permission denial on a screen that is theirs.
 *
 * Same rules as `make-catalog-seed.mjs`, for the same reasons:
 *
 *  - **Foreign keys travel as slugs, never ids.** The two databases were
 *    seeded independently and their `pillars.id` values do not line up;
 *    copying raw ids would file "School supplies" against whichever programme
 *    happened to hold that number.
 *  - **Idempotent by construction.** Every insert is keyed on the row's
 *    natural key and skipped when it is already there, so re-running adds what
 *    is missing and overwrites nothing a staff member has since edited —
 *    including a category they have paused or renamed.
 *
 *   node scripts/make-inkind-seed.mjs   # writes deploy/seed-inkind.mjs
 */
import Database from 'better-sqlite3';
import fs from 'node:fs';
import path from 'node:path';

const url = process.env.DATABASE_URL;
if (!url) throw new Error('DATABASE_URL is not set');

const db = new Database(url, { readonly: true });

const rows = (sql) => db.prepare(sql).all();

/** Resolves a foreign key to the slug of the row it points at. */
const slugFor = (table, id) => {
	if (id === null || id === undefined) return null;
	return db.prepare(`select slug from ${table} where id = ?`).get(id)?.slug ?? null;
};

/* ==========================================================================
   Collect
   ========================================================================== */

const payload = {
	categories: rows(
		`select slug, name, name_am, description, icon, pillar_id, default_unit,
		        requires_expiry, requires_sizing, requires_transport, acceptance_note,
		        is_accepting_now, sort_order
		 from in_kind_categories where deleted_at is null order by sort_order`
	).map((row) => ({
		...row,
		pillar_id: undefined,
		pillar_slug: slugFor('pillars', row.pillar_id)
	})),

	// Name-keyed rather than slug-keyed: `permissions.name` is the natural key
	// and the string the code checks against.
	permissions: rows(
		`select name, description, "group" from permissions where name like 'inkind.%' order by name`
	),

	// Which role holds which of them, both sides named rather than numbered.
	grants: rows(
		`select r.slug as role_slug, p.name as permission_name
		 from role_permissions rp
		 join roles r on r.id = rp.role_id
		 join permissions p on p.id = rp.permission_id
		 where p.name like 'inkind.%'
		 order by r.slug, p.name`
	)
};

/* ==========================================================================
   Sanity — a silent empty payload would deploy a blank form
   ========================================================================== */

if (payload.categories.length < 10) {
	throw new Error(
		`expected the seeded gift categories locally, found ${payload.categories.length}. ` +
			'Run `npm run db:seed` first.'
	);
}
if (payload.permissions.length !== 2) {
	throw new Error(
		`expected inkind.read and inkind.write locally, found ${payload.permissions.length}. ` +
			'Run `npm run db:seed` first.'
	);
}
if (payload.grants.length === 0) {
	throw new Error('no role holds the in-kind permissions locally — re-seed before generating');
}

/* ==========================================================================
   Emit
   ========================================================================== */

const script = `/**
 * Seeds the in-kind giving catalogue on the server.
 *
 * GENERATED by scripts/make-inkind-seed.mjs — do not edit by hand.
 *
 * Configuration rows only: the categories the "Give goods" tab is built from,
 * and the two permissions the in-kind dashboard checks. No donations, no
 * content, nothing the Foundation has not asked for.
 *
 * Idempotent. Every insert is keyed on the row's natural key and skipped when
 * it is already there, so re-running adds what is missing and overwrites
 * nothing anyone has edited since — a category paused or renamed on the
 * server stays paused and renamed.
 *
 *   node seed-inkind.mjs
 */
import Database from 'better-sqlite3';

const db = new Database('local.db');
db.pragma('foreign_keys = ON');

const data = ${JSON.stringify(payload, null, '\t')};

const now = () => Date.now();
let added = 0;
let skipped = 0;

const idBySlug = (table, slug) =>
	slug ? (db.prepare(\`select id from \${table} where slug = ?\`).get(slug)?.id ?? null) : null;

db.transaction(() => {
	/* --- The catalogue behind the goods form ---------------------------- */
	for (const row of data.categories) {
		const existing = db
			.prepare('select id from in_kind_categories where slug = ?')
			.get(row.slug);
		if (existing) {
			skipped++;
			continue;
		}

		db.prepare(
			\`insert into in_kind_categories
			   (slug, name, name_am, description, icon, pillar_id, default_unit,
			    requires_expiry, requires_sizing, requires_transport, acceptance_note,
			    is_accepting_now, sort_order, is_active, created_at, updated_at)
			 values (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, ?, ?)\`
		).run(
			row.slug,
			row.name,
			row.name_am,
			row.description,
			row.icon,
			// Resolved on this database. A programme that does not exist here
			// leaves the category unrouted rather than pointing it at the wrong one.
			idBySlug('pillars', row.pillar_slug),
			row.default_unit,
			row.requires_expiry,
			row.requires_sizing,
			row.requires_transport,
			row.acceptance_note,
			row.is_accepting_now,
			row.sort_order,
			now(),
			now()
		);
		added++;
	}

	/* --- The permissions the in-kind screens check ----------------------- */
	for (const permission of data.permissions) {
		const existing = db.prepare('select id from permissions where name = ?').get(permission.name);
		if (existing) {
			skipped++;
			continue;
		}
		db.prepare('insert into permissions (name, description, "group") values (?, ?, ?)').run(
			permission.name,
			permission.description,
			permission.group
		);
		added++;
	}

	/* --- and who holds them ------------------------------------------------
	   super_admin is a wildcard resolved in code and has no rows, which is why
	   only the scoped roles appear here. A role that does not exist on this
	   server is skipped rather than created. */
	for (const grant of data.grants) {
		const roleId = idBySlug('roles', grant.role_slug);
		const permission = db
			.prepare('select id from permissions where name = ?')
			.get(grant.permission_name);
		if (!roleId || !permission) {
			skipped++;
			continue;
		}

		const existing = db
			.prepare('select id from role_permissions where role_id = ? and permission_id = ?')
			.get(roleId, permission.id);
		if (existing) {
			skipped++;
			continue;
		}

		db.prepare(
			\`insert into role_permissions (role_id, permission_id, is_active, created_at, updated_at)
			 values (?, ?, 1, ?, ?)\`
		).run(roleId, permission.id, now(), now());
		added++;
	}
})();

console.log(\`in-kind seed: \${added} rows added, \${skipped} already present\`);

const counts = db
	.prepare(
		\`select
		   (select count(*) from in_kind_categories where deleted_at is null) as categories,
		   (select count(*) from permissions where name like 'inkind.%') as permissions\`
	)
	.get();
console.log(\`  \${counts.categories} gift categories, \${counts.permissions} permissions in place\`);

db.close();
`;

const out = path.join(process.cwd(), 'deploy', 'seed-inkind.mjs');
fs.writeFileSync(out, script);
console.log(`wrote ${out}`);
console.log(
	`  ${payload.categories.length} gift categories, ${payload.permissions.length} permissions, ` +
		`${payload.grants.length} role grants`
);

db.close();
