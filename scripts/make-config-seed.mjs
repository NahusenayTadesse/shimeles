/**
 * Emits a standalone seeder for site settings, UI strings and the application
 * workflow statuses.
 *
 * The gap the other two generators leave. `make-catalog-seed.mjs` carries the
 * public-form vocabularies and the *contact* statuses; `make-inkind-seed.mjs`
 * carries the gift categories. Neither carries `site_settings`, `translations`
 * or the `application` statuses — so a release that adds a setting the page
 * renders from ships a page that renders nothing, silently, with no error to
 * notice. The future-initiatives legal disclaimer is exactly that shape: a
 * missing row is an empty string, and an empty string is no notice at all.
 *
 * Same two rules as its siblings, for the same reasons:
 *
 *  - **Idempotent by construction.** Every insert is keyed on the row's natural
 *    key — `key` for settings and strings, `(context, stage)` for statuses —
 *    and skipped when it is already there. Re-running adds what is missing.
 *  - **Never overwrites a value.** `site_settings.value` and `translations.en`
 *    are what staff last saved from the dashboard. A deploy that "corrects"
 *    them would silently undo somebody's edit, so an existing row is left
 *    entirely alone, metadata included.
 *
 * There are no foreign keys here, so unlike its siblings this one has no slugs
 * to resolve.
 *
 *   node scripts/make-config-seed.mjs   # writes deploy/seed-config.mjs
 */
import Database from 'better-sqlite3';
import fs from 'node:fs';
import path from 'node:path';

const url = process.env.DATABASE_URL;
if (!url) throw new Error('DATABASE_URL is not set');

const db = new Database(url, { readonly: true });

const rows = (sql) => db.prepare(sql).all();

/* ==========================================================================
   Collect
   ========================================================================== */

const payload = {
	settings: rows(
		`select key, value, value_type, label, hint, "group", sort_order
		 from site_settings where deleted_at is null order by "group", sort_order`
	),

	strings: rows(
		`select key, en, "group" from translations where deleted_at is null order by "group", key`
	),

	/**
	 * Assistance-application statuses. `make-catalog-seed.mjs` takes only the
	 * `contact` context, so this is the half that has never had a way across.
	 */
	applicationStatuses: rows(
		`select context, stage, label, color, public_description, is_default, sort_order
		 from status_options
		 where context in ('application', 'volunteer') and deleted_at is null
		 order by context, sort_order`
	)
};

db.close();

/* ==========================================================================
   Sanity — a generator that silently emits nothing is worse than one that
   throws, because the deploy carries on and the page is blank on the server.
   ========================================================================== */

const expected = { settings: 20, strings: 20, applicationStatuses: 10 };

for (const [key, min] of Object.entries(expected)) {
	if (!payload[key] || payload[key].length < min) {
		throw new Error(`expected at least ${min} ${key} locally, found ${payload[key]?.length ?? 0}`);
	}
}

/** The rows this release exists to carry. Absent locally means a missed seed. */
const required = ['initiatives.disclaimer'];
for (const key of required) {
	if (!payload.settings.some((row) => row.key === key)) {
		throw new Error(`setting "${key}" is missing locally — run \`npm run db:seed\` first`);
	}
}
if (!payload.applicationStatuses.some((row) => row.stage === 'waitlisted')) {
	throw new Error('the waitlisted application status is missing locally — run `npm run db:seed`');
}

/* ==========================================================================
   Emit
   ========================================================================== */

const script = `/**
 * Seeds site settings, UI strings and application statuses on the server.
 *
 * GENERATED by scripts/make-config-seed.mjs — do not edit by hand.
 *
 * Idempotent, and deliberately timid: a row whose natural key is already there
 * is left exactly as it is, value and metadata alike, because those are what
 * staff last saved from the dashboard.
 *
 *   node seed-config.mjs
 */
import Database from 'better-sqlite3';

const db = new Database('local.db');
db.pragma('foreign_keys = ON');

const data = ${JSON.stringify(payload, null, '\t')};

const now = () => Date.now();
let added = 0;
let skipped = 0;

db.transaction(() => {
	/* --- Site settings --------------------------------------------------- */
	for (const row of data.settings) {
		const existing = db.prepare('select id from site_settings where key = ?').get(row.key);
		if (existing) {
			skipped++;
			continue;
		}
		db.prepare(
			\`insert into site_settings (key, value, value_type, label, hint, "group", sort_order,
			                            is_active, created_at, updated_at)
			 values (?, ?, ?, ?, ?, ?, ?, 1, ?, ?)\`
		).run(
			row.key,
			row.value,
			row.value_type,
			row.label,
			row.hint,
			row.group,
			row.sort_order,
			now(),
			now()
		);
		added++;
	}

	/* --- UI strings ------------------------------------------------------- */
	for (const row of data.strings) {
		const existing = db.prepare('select id from translations where key = ?').get(row.key);
		if (existing) {
			skipped++;
			continue;
		}
		db.prepare(
			\`insert into translations (key, en, "group", is_active, created_at, updated_at)
			 values (?, ?, ?, 1, ?, ?)\`
		).run(row.key, row.en, row.group, now(), now());
		added++;
	}

	/* --- Application and volunteer workflow statuses ---------------------- */
	for (const row of data.applicationStatuses) {
		const existing = db
			.prepare('select id from status_options where context = ? and stage = ?')
			.get(row.context, row.stage);
		if (existing) {
			skipped++;
			continue;
		}
		// Never steal the default from a status production already has: two
		// defaults in one context is a coin toss over where new records land.
		const hasDefault = db
			.prepare('select id from status_options where context = ? and is_default = 1')
			.get(row.context);

		db.prepare(
			\`insert into status_options (context, stage, label, color, public_description,
			                             is_default, sort_order, is_active, created_at, updated_at)
			 values (?, ?, ?, ?, ?, ?, ?, 1, ?, ?)\`
		).run(
			row.context,
			row.stage,
			row.label,
			row.color,
			row.public_description,
			hasDefault ? 0 : row.is_default,
			row.sort_order,
			now(),
			now()
		);
		added++;
	}
})();

console.log(\`config seed: \${added} rows added, \${skipped} already present\`);
db.close();
`;

const out = path.join(process.cwd(), 'deploy', 'seed-config.mjs');
fs.writeFileSync(out, script);
console.log(`wrote ${out}`);
console.log(
	`  ${payload.settings.length} settings, ${payload.strings.length} strings, ` +
		`${payload.applicationStatuses.length} statuses`
);
